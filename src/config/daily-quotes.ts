/** 오늘 날짜(YYYY-MM-DD)에 해당하는 문구. 연중 일수로 순환 */
export function quoteForDate(dateStr: string): DailyQuote {
  const d = new Date(dateStr + 'T00:00:00');
  const start = new Date(d.getFullYear(), 0, 0);
  const dayOfYear = Math.floor((d.getTime() - start.getTime()) / 86400000);
  // 해마다 시작점이 조금 달라지도록 연도를 섞는다
  const idx = (dayOfYear + d.getFullYear() * 7) % DAILY_QUOTES.length;
  return DAILY_QUOTES[idx];
}
