/** 시공 기록의 종류와 작업 내역서 항목 묶음(PPF·썬팅·컬러PPF·랩핑·코팅·패키지…)에서 보여 줄 안내를 고른다 */
export function careGuidesFor(serviceTypes: string[], itemGroups: string[] = []): CareGuide[] {
  const keys = new Set<string>();
  const add = (k: string) => { if (CARE_GUIDES.some((g) => g.key === k)) keys.add(k); };
  for (const raw of [...serviceTypes, ...itemGroups]) {
    const t = (raw || '').replace(/\s+/g, '');
    if (!t) continue;
    if (/컬러PPF|PWF/i.test(t)) add('컬러PPF');
    else if (/실내PPF/i.test(t)) add('실내PPF');
    else if (/PPF/i.test(t)) add('PPF');
    if (/랩핑/.test(t)) add('랩핑');
    if (/크롬/.test(t)) add('크롬죽이기');
    if (/썬팅|틴팅/.test(t)) add('썬팅');
    if (/유리막|코팅/.test(t)) add('유리막코팅');
    if (/신차패키지/.test(t)) { add('썬팅'); add('PPF'); add('유리막코팅'); } // 패키지는 보통 썬팅+PPF+코팅. 작업 내역서 항목이 있으면 그쪽이 더 정확
  }
  return CARE_GUIDES.filter((g) => keys.has(g.key));
}
